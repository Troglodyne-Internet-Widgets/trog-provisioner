package Provisioner::Recipe::vm;

#ABSTRACT: The machine a guest runs on, rather than what runs on it.

use 5.041;

use strict;
use warnings FATAL => 'all';
use re '/aa';

use parent qw{Provisioner::Recipe};

use File::Slurper();
use Trog::HV();

=head1 NAME

Provisioner::Recipe::vm - the virtual machine itself: how big it is, what its
disks will take, and the hypervisor XML that defines it.

=head1 SYNOPSIS

    _base:
        _global:
            memory: 8192
            cpus:   4
            size:   85899345920
            disk_cache: none
            disk_total_iops_sec: 2000

=head1 DESCRIPTION

Every other recipe describes something that runs I<on> a guest.  This one
describes the guest: how much memory and how many CPUs it is promised, how large
its disk is, and every knob that decides how qemu carries its I/O.

It renders the libvirt domain XML, which is the one file here that cannot be
written until a hypervisor has answered for itself -- so unlike every other
recipe's generated files, this one is generated by C<bin/provision> rather than
by C<bin/new_config>.  See L</WHEN IT IS GENERATED>.

Its settings live in a domain's C<_global>, and are copied from there into
F<provision.conf>, which is what C<bin/provision> reads.  C<bin/recipes vm>
prints this schema, which is the description of them: F<example.test/provision.conf>
lists the keys and points here.

=head2 It directs the build rather than running in it

C<is_module> is false: there is no makefile fragment, because everything here
happens before the guest exists to run a makefile.  Every distro recipe depends
on this one -- see L<Provisioner::DistroRecipe>.

=head2 Nothing is emitted blind

libvirt has accepted most of these attributes for longer than qemu has
implemented them, so a knob this hypervisor is too old for is a domain that
either defines and will not start or starts and quietly does something else.
C<enrich> therefore asks L<Trog::HV/supports> about each one and leaves out what
this machine will not take, saying so on the way past.

The exception is the throttles.  Every other knob failing open leaves a guest
merely untuned; a throttle silently not applied leaves somebody believing in a
limit that is not there, so an unsupported one is fatal.

=head2 WHEN IT IS GENERATED

The XML names a storage volume, a backing image and a seed ISO, and it names
them by paths that do not exist until they have been made.  C<create_storage>
makes them and hands back what the template needs; C<generate_files> then
renders as any other recipe does.  Both are called from C<bin/provision>, which
is the program that has a hypervisor in hand.

The seam is deliberate.  Everything libvirt-shaped is in this recipe and its
template, so a second virtualisation platform is another recipe and another
template rather than a rewrite of C<bin/provision>.

=cut

# The limits, in the order libvirt wants them.
my @IOTUNE_KEY = qw{
  total_bytes_sec read_bytes_sec write_bytes_sec
  total_iops_sec  read_iops_sec  write_iops_sec
};

=head1 METHODS

=head2 $bool = $recipe->is_module()

False.  See L</It directs the build rather than running in it>.

=cut

sub is_module { return 0 }

=head2 %args = $recipe->args()

What a guest's machine takes.

The C<disk_*> ones deliberately declare B<no defaults>.  A default here would be
written into F<provision.conf> by C<bin/new_config>, and an absent key is how a
guest says "whatever this hypervisor decides" -- which is the whole point of
asking the hypervisor.  Their real defaults are in C<enrich>, where the answer
can depend on what libvirt and qemu will take.

=cut

